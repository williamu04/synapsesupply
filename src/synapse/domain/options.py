"""Enumerate ways to cover a shortfall and score how well a chosen one fits.

Options are computed, not generated by the model: every arrival date, cost and compliance verdict
here is reproducible from ERP data. The agent chooses among them and explains the choice; it cannot
invent an option or a number (`submit_action` only accepts an `option_id` from this list).
"""
from dataclasses import dataclass, field
from datetime import date, timedelta

from . import compliance

PASSING = ("PASS", "NOT_APPLICABLE")
_COMPLIANCE_RANK = {"PASS": 0, "NOT_APPLICABLE": 0, "HOLD": 1, "BLOCK": 2}


@dataclass(frozen=True)
class SourcingOption:
    option_id: str          # "PO:<supplier>" or "STO:<plant>"
    kind: str               # PURCHASE_ORDER | STOCK_TRANSFER
    source: str             # supplier number or supplying plant
    source_name: str
    unit_cost: float        # net price (PO) or freight (transfer), USD per unit
    incremental_cost_per_unit: float  # vs. the price of the delayed order
    lead_days: int
    earliest_arrival: date
    arrives_in_time: bool
    max_quantity: float | None
    compliance: str         # PASS | HOLD | BLOCK | NOT_APPLICABLE
    compliance_findings: list[str] = field(default_factory=list)

    def incremental_cost(self, quantity: float) -> float:
        return round(max(0.0, self.incremental_cost_per_unit) * quantity, 2)


def sourcing_options(*, plant: str, material: str, quantity: float, needed_by: date, today: date,
                     baseline_price: float, info_records: list[dict], compliance_profiles: dict[str, dict],
                     lanes: list[dict], donor_spare: dict[str, float], plant_names: dict[str, str]
                     ) -> list[SourcingOption]:
    """All purchase and transfer options for (plant, material), best first.

    donor_spare: per other plant, how much it can give without its own projection falling
    below its safety stock (computed by the caller from that plant's data).
    """
    options = []
    for rec in info_records:
        if (rec["Plant"], rec["Material"]) != (plant, material):
            continue
        profile = compliance_profiles.get(rec["Supplier"])
        checks = compliance.evaluate(profile, quantity, today)
        arrival = today + timedelta(days=rec["MaterialPlannedDeliveryDurn"])
        price = float(rec["NetPriceAmount"])
        options.append(SourcingOption(
            option_id=f"PO:{rec['Supplier']}", kind="PURCHASE_ORDER", source=rec["Supplier"],
            source_name=(profile or {}).get("SupplierName", rec["Supplier"]), unit_cost=price,
            incremental_cost_per_unit=round(price - baseline_price, 2), lead_days=rec["MaterialPlannedDeliveryDurn"],
            earliest_arrival=arrival, arrives_in_time=arrival <= needed_by, max_quantity=None,
            compliance=compliance.outcome(checks),
            compliance_findings=[f"{c.code}: {c.detail}" for c in checks if not c.passed]))

    for lane in lanes:
        if (lane["ToPlant"], lane["Material"]) != (plant, material) or lane["FromPlant"] not in donor_spare:
            continue
        donor = lane["FromPlant"]
        arrival = today + timedelta(days=lane["TransitDays"])
        cap = min(float(lane["MaxDailyQty"]), max(0.0, donor_spare[donor]))
        freight = float(lane["CostPerUnit"])
        options.append(SourcingOption(
            option_id=f"STO:{donor}", kind="STOCK_TRANSFER", source=donor,
            source_name=plant_names.get(donor, donor), unit_cost=freight, incremental_cost_per_unit=freight,
            lead_days=lane["TransitDays"], earliest_arrival=arrival, arrives_in_time=arrival <= needed_by,
            max_quantity=round(cap, 3), compliance="NOT_APPLICABLE"))

    return sorted(options, key=lambda o: (not o.arrives_in_time, _COMPLIANCE_RANK[o.compliance],
                                          o.incremental_cost_per_unit, o.option_id))


def plan_confidence(*, covers_shortfall: bool, arrives_in_time: bool, demand_samples: int,
                    lead_time_samples: int, erp_degraded: bool, late_risk: float | None = None) -> float:
    """Evidence quality and plan fit — not the model's self-assessment.

    Starts at 0.97 (synthetic-data humility) and is reduced for each weakness. Cedar auto-executes
    only at >= 0.90, so any single material weakness sends the plan to a human.
    """
    c = 0.97
    if not covers_shortfall:
        c -= 0.15
    if not arrives_in_time:
        c -= 0.20
    if demand_samples < 30:
        c -= 0.05
    if lead_time_samples < 10:
        c -= 0.05
    if erp_degraded:
        c -= 0.10
    if late_risk is not None and late_risk >= 0.5:  # predicted more likely late than on time
        c -= 0.10
    return round(max(c, 0.0), 2)
